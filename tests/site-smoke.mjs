import assert from 'node:assert/strict'
import { chromium, request } from 'playwright'
import { MongoClient } from 'mongodb'
const base = 'http://127.0.0.1:3131'
async function main() {
  const api = await request.newContext({ baseURL: base })
  const invalid = await api.post('/api/book', { data: {} })
  assert.equal(invalid.status(), 400, 'invalid booking rejected')
  const booking = { name: 'Test Visitor', email: 'visitor@example.invalid', type: 'scuba_course', activity: 'CI test course', date: '2035-05-15', time: '10:00' }
  const created = await api.post('/api/book', { data: booking })
  assert.equal(created.status(), 200, `booking status: ${await created.text()}`)
  assert.equal((await created.json()).status, 'pending')
  const mongo = new MongoClient('mongodb://127.0.0.1:27017')
  await mongo.connect()
  const collection = mongo.db('scuba_booking').collection('scuba_bookings')
  const saved = await collection.findOne({ email: booking.email, activity: { $exists: false }, course: booking.activity })
  assert.ok(saved, 'pending booking stored in isolated database')
  await collection.updateOne({ _id: saved._id }, { $set: { status: 'approved' } })
  const availability = await api.get(`/api/availability?date=${booking.date}&type=${booking.type}&activity=${encodeURIComponent(booking.activity)}`)
  assert.deepEqual((await availability.json()).bookedTimes, ['10:00'])
  const conflict = await api.post('/api/book', { data: { ...booking, time: '11:00' } })
  assert.equal(conflict.status(), 400, 'overlapping booking rejected')
  const invalidContact = await api.post('/api/contact', { data: {} })
  assert.equal(invalidContact.status(), 400)
  const contact = await api.post('/api/contact', { data: { name: 'Test Visitor', email: 'visitor@example.invalid', subject: 'CI test', message: 'This is an isolated test message.' } })
  assert.equal(contact.status(), 200, `contact status: ${await contact.text()}`)
  assert.equal((await contact.json()).confirmationSent, true)
  const failedContact = await api.post('/api/contact', { data: { name: 'Test Visitor', email: 'visitor@example.invalid', subject: 'CI simulated mail failure', message: 'This is an isolated test message.' } })
  assert.equal(failedContact.status(), 502, 'contact reports simulated mail failure')
  await mongo.close()
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] })
  for (const size of [{ width: 390, height: 844 }, { width: 1440, height: 900 }]) {
    const page = await browser.newPage({ viewport: size })
    const paths = ['/', '/ru', '/activities', '/ru/activities', '/destinations', '/ru/destinations', '/destinations/thailand', '/ru/destinations/thailand', '/destinations/maldives', '/ru/destinations/maldives', '/destinations/maldives/wella-giri', '/ru/destinations/maldives/wella-giri', '/scubadivingcourses', '/ru/scubadivingcourses', '/snorkeling', '/ru/snorkeling', '/blog', '/ru/blog', '/contact', '/ru/contact']
    for (const path of paths) {
      const response = await page.goto(base + path, { waitUntil: 'domcontentloaded' })
      assert.equal(response.status(), 200, `${size.width} ${path} response`)
      assert.ok(await page.locator('h1').count(), `${size.width} ${path} has heading`)
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)
      assert.ok(overflow <= 2, `${size.width} ${path} horizontal overflow: ${overflow}`)
      if (path.endsWith('/wella-giri')) {
        const story = page.locator('#wella-story-title')
        await story.scrollIntoViewIfNeeded()
        assert.ok(await story.isVisible(), `${size.width} ${path} story heading visible`)
        assert.equal(await page.locator('a[href="#dive-conditions"]').count(), 1, `${size.width} ${path} conditions link`)
        assert.equal(await page.locator('#dive-conditions').count(), 1, `${size.width} ${path} conditions target`)
        assert.equal(await page.locator('section[aria-labelledby="wella-story-title"] img').count(), 2, `${size.width} ${path} story photographs`)
      }
    }
    await page.goto(base + '/ru/scubadivingcourses')
    const open = page.getByRole('button', { name: /записаться|забронировать/i }).first()
    await open.click()
    assert.ok(await page.getByPlaceholder('Эл. почта').isVisible(), 'Russian booking form translated')
    const form = page.locator('form').filter({ has: page.getByPlaceholder('Эл. почта') })
    await form.getByPlaceholder('Имя').fill('Тест')
    await form.getByPlaceholder('Эл. почта').fill('browser@example.invalid')
    await form.locator('input[type=date]').fill('2035-05-16')
    await form.locator('select').selectOption('14:00')
    await form.getByRole('button', { name: 'Отправить заявку' }).click()
    await page.getByRole('status').filter({ hasText: 'Заявка получена.' }).waitFor()
    await page.goto(base + '/')
    const carousel = page.getByRole('region', { name: 'Dive and snorkel videos' })
    await carousel.scrollIntoViewIfNeeded()
    const first = async () => carousel.locator('a').first().getAttribute('href')
    let before = await first()
    await carousel.getByRole('button', { name: 'Next', exact: true }).click()
    await page.waitForTimeout(800)
    assert.notEqual(await first(), before, 'carousel next advances')
    await page.evaluate(() => document.activeElement instanceof HTMLElement && document.activeElement.blur())
    await page.mouse.move(1, 1)
    before = await first()
    await page.waitForTimeout(5000)
    assert.notEqual(await first(), before, 'carousel advances automatically')
    await carousel.hover()
    await page.waitForTimeout(500)
    before = await first()
    await page.waitForTimeout(4500)
    assert.equal(await first(), before, 'hover pauses carousel')
    await carousel.getByRole('button', { name: 'Pause automatic slides' }).click()
    await page.evaluate(() => document.activeElement instanceof HTMLElement && document.activeElement.blur())
    await page.mouse.move(1, 1)
    before = await first()
    await page.waitForTimeout(4500)
    assert.equal(await first(), before, 'carousel pause stops autoplay')
    if (size.width === 390) {
      before = await first()
      await carousel.locator('.overflow-hidden').first().evaluate(el => {
        const start = new Touch({ identifier: 1, target: el, clientX: 300, clientY: 100 })
        const end = new Touch({ identifier: 1, target: el, clientX: 100, clientY: 100 })
        el.dispatchEvent(new TouchEvent('touchstart', { bubbles: true, touches: [start], changedTouches: [start] }))
        el.dispatchEvent(new TouchEvent('touchend', { bubbles: true, touches: [], changedTouches: [end] }))
      })
      await page.waitForTimeout(800)
      assert.notEqual(await first(), before, 'emulated touch swipe advances carousel')
    }
    await page.close()
  }
  const reduced = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  await reduced.goto(base + '/')
  const reducedCarousel = reduced.getByRole('region', { name: 'Dive and snorkel videos' })
  await reducedCarousel.scrollIntoViewIfNeeded()
  const firstReduced = await reducedCarousel.locator('a').first().getAttribute('href')
  await reduced.waitForTimeout(4500)
  assert.equal(await reducedCarousel.locator('a').first().getAttribute('href'), firstReduced, 'reduced motion disables autoplay')
  await reducedCarousel.getByRole('button', { name: 'Next', exact: true }).click()
  assert.notEqual(await reducedCarousel.locator('a').first().getAttribute('href'), firstReduced, 'manual navigation works with reduced motion')
  await browser.close()
  await api.dispose()
  console.log('PASS: isolated booking, contact, responsive route and carousel smoke checks')
}
main().catch(error => { console.error(error); process.exit(1) })
